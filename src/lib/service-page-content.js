export function mergeServicePageContent(serviceId, databasePage = {}) {
  const sourcePage = servicePageContent[serviceId] || {};
  const mergedPage = {
    ...sourcePage,
    ...databasePage,
  };

  for (const key of Object.keys(sourcePage)) {
    if (
      sourcePage[key] &&
      databasePage[key] &&
      typeof sourcePage[key] === "object" &&
      !Array.isArray(sourcePage[key]) &&
      typeof databasePage[key] === "object" &&
      !Array.isArray(databasePage[key])
    ) {
      mergedPage[key] = {
        ...sourcePage[key],
        ...databasePage[key],
      };
    }
  }

  return mergedPage;
}
